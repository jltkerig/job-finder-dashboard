"""Writes a map of the project's source files: each file's size and purpose, and for big files the names and line numbers
of their functions or sections, so a change can be found without reading whole files.
usage: python scripts/code_map.py [output file]   (run from the project folder; output defaults to docs/CODE-MAP.md)"""
import ast
import os
import re
import sys

ROOT = os.getcwd()
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join("docs", "CODE-MAP.md")
SKIP = {"node_modules", "__pycache__", ".git", "dist", "user-data", "docs", ".build", "searches", "user-builds", "logs",
        "test-results", "tests", "data", "icons", "graphify-out"}
EXTS = {".py", ".js", ".php", ".html", ".css", ".mjs"}
DETAIL_LINES = 400  # files longer than this list their functions / sections


def first_purpose(text, ext):
    if ext == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text))
        except SyntaxError:
            doc = None
        if doc:
            return " ".join(doc.split("\n\n")[0].split())[:95]
    for line in text.splitlines()[:12]:
        line = line.strip()
        if ext == ".css" and not line.startswith("/*"):
            continue
        m = re.match(r"^(?://+|#|/\*+|\*|<\?php\s*//|<!--)\s*(.+?)(?:\*/|-->)?$", line)
        if m and not m.group(1).startswith(("!", "-*-", "eslint", "use strict")):
            return m.group(1).strip(" */")[:95]
    return ""


def outline(text, ext):
    rows = []
    lines = text.splitlines()
    if ext == ".py":
        try:
            tree = ast.parse(text)
        except SyntaxError:
            return rows
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                rows.append((node.lineno, node.name))
    elif ext in (".js", ".mjs"):
        for i, line in enumerate(lines, 1):
            m = re.match(r"^(?:\s{0,2})(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)", line)
            if m:
                rows.append((i, m.group(1)))
    elif ext == ".php":
        for i, line in enumerate(lines, 1):
            m = re.match(r"^function\s+([A-Za-z_]\w*)", line)
            if m:
                rows.append((i, m.group(1)))
    elif ext == ".css":
        for i, line in enumerate(lines, 1):
            m = re.match(r"^/\*\s*(.+?)\s*\*/\s*$", line)
            if m:
                rows.append((i, m.group(1)[:90]))
    return rows


def main():
    entries = []
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(d for d in dirs if d not in SKIP and not d.startswith("."))
        for name in sorted(files):
            ext = os.path.splitext(name)[1]
            if ext not in EXTS:
                continue
            path = os.path.join(base, name)
            try:
                text = open(path, encoding="utf-8", errors="ignore").read()
            except OSError:
                continue
            entries.append((os.path.relpath(path, ROOT).replace("\\", "/"), text, ext))
    out = [f"# Code map\n",
           "Generated by `scripts/code_map.py`; run it again after adding or moving files. Lists every source file with its size and purpose, and",
           f"for files over {DETAIL_LINES} lines the line numbers of their functions (or, for style sheets, their sections), so a change can be",
           "found with a search and a short read instead of opening whole files. Search this file (grep) for a feature; do not read it whole.\n"]
    folder = None
    for rel, text, ext in entries:
        parent = os.path.dirname(rel) or "."
        if parent != folder:
            folder = parent
            out.append(f"\n## {parent}/\n")
        n = text.count("\n") + 1
        out.append(f"- `{os.path.basename(rel)}` ({n} lines){': ' + first_purpose(text, ext) if first_purpose(text, ext) else ''}")
        if n > DETAIL_LINES:
            rows = outline(text, ext)
            if rows:
                out.append("  - " + "; ".join(f"{name} {line}" for line, name in rows))
    os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(f"{OUT}: {len(entries)} files, {sum(len(e[1]) for e in entries) // 1024} KB of source")


main()
